/**
 * Writes `docs/adr/README.md`, the list of the ADRs in force, and checks that
 * the list and the folder agree.
 *
 *   node scripts/adr-index.mjs           write the index
 *   node scripts/adr-index.mjs --check   print each problem, exit 1 if any
 *
 * An ADR is in force unless its `status` front matter says `superseded`, or
 * `deprecated` when nothing replaces it. `pnpm docs:check` runs the check;
 * `pnpm adr:index` writes the index. The check fails when
 * - the index differs from the one the ADRs generate,
 * - a retired ADR is not in `docs/adr/retired/`, or an ADR in force is.
 *
 * Uses only `node:` modules.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ADR_DIR = "docs/adr";
const RETIRED_DIR = "retired";
const INDEX = `${ADR_DIR}/README.md`;

function adrFiles(root, dir) {
  const full = path.join(root, dir);
  if (!fs.existsSync(full)) return [];
  return fs
    .readdirSync(full)
    .filter((name) => /^\d{4}-.*\.md$/.test(name))
    .sort()
    .map((name) => `${dir}/${name}`);
}

function readAdr(root, file) {
  const text = fs.readFileSync(path.join(root, file), "utf8");
  const frontMatter = /^---\n((?:.*\n)*?)---\n/.exec(text)?.[1] ?? "";
  const status = /^status:[ \t]*(.*)$/m.exec(frontMatter)?.[1].trim();
  const title = /^# (.+)$/m.exec(text)?.[1].trim();
  const number = /\/(\d{4})-/.exec(file)[1];
  return {
    file,
    number,
    status,
    title,
    retired: file.includes(`/${RETIRED_DIR}/`),
  };
}

function allAdrs(root) {
  return [
    ...adrFiles(root, ADR_DIR),
    ...adrFiles(root, `${ADR_DIR}/${RETIRED_DIR}`),
  ].map((file) => readAdr(root, file));
}

/** How an ADR left force, by the start of its status, or undefined while in force. */
const retiredAs = (adr) =>
  ["superseded", "deprecated"].find((word) => adr.status?.startsWith(word));
const outOfForce = (adr) => retiredAs(adr) !== undefined;

/** The text of `docs/adr/README.md`: every ADR in force, by number. */
export function adrIndexText(root, adrs = allAdrs(root)) {
  const inForce = adrs.filter((adr) => !outOfForce(adr));
  const items = inForce.map(
    ({ file, number, title }) =>
      `- [ADR-${number}: ${title}](${path.posix.relative(ADR_DIR, file)})`
  );
  return [
    "# Architecture decision records",
    "",
    "The ADRs in force. Read [AGENTS.md](AGENTS.md) before writing or replacing one; it holds the rules.",
    "A replaced or deprecated ADR lives in [retired/](retired/), its text unchanged.",
    "",
    "<!-- Generated by `pnpm adr:index`; do not edit. `pnpm docs:check` fails when it is out of date. -->",
    "",
    ...items,
    "",
  ].join("\n");
}

/** What is wrong with the ADR folder: a stale index, an ADR in the wrong folder. */
export function checkAdrIndex(root) {
  const problems = [];
  const adrs = allAdrs(root);
  for (const adr of adrs) {
    if (adr.status === undefined)
      problems.push(`${adr.file}: no \`status\` in the front matter`);
    else if (outOfForce(adr) && !adr.retired)
      problems.push(
        `${adr.file}: ${retiredAs(adr)}, so it belongs in ${ADR_DIR}/${RETIRED_DIR}/`
      );
    else if (!outOfForce(adr) && adr.retired)
      problems.push(
        `${adr.file}: in force, so it does not belong in ${ADR_DIR}/${RETIRED_DIR}/`
      );
  }
  const indexFile = path.join(root, INDEX);
  const current = fs.existsSync(indexFile)
    ? fs.readFileSync(indexFile, "utf8")
    : undefined;
  if (current !== adrIndexText(root, adrs))
    problems.push(`${INDEX}: out of date, run \`pnpm adr:index\``);
  return problems;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  if (process.argv.includes("--check")) {
    const problems = checkAdrIndex(root);
    for (const problem of problems) console.error(problem);
    process.exit(problems.length === 0 ? 0 : 1);
  }
  fs.writeFileSync(path.join(root, INDEX), adrIndexText(root));
  console.log(`wrote ${INDEX}`);
}
